// Regenerates src/styles/fonts.css from the @fontsource packages.
// Run after updating a font package:  node scripts/build-fonts-css.mjs
// Keeps only woff2 files (every current browser supports them) and only the
// character sets the site needs, so the build stays small. Browsers download
// a font file only when a page actually uses characters from its range.
import { readFileSync, writeFileSync } from 'node:fs';

const sets = [
  // [package, weights, keep only these subsets (null = all)]
  ['varela-round', [400], ['latin', 'latin-ext']],
  ['inter', [400, 500, 600, 700], ['latin', 'latin-ext']],
  ['noto-sans-kr', [400, 500, 600, 700], null], // Korean is split into many small ranges
];

let out = '/* Generated by scripts/build-fonts-css.mjs — do not edit by hand. */\n';
for (const [pkg, weights, keep] of sets) {
  for (const w of weights) {
    const css = readFileSync(`node_modules/@fontsource/${pkg}/${w}.css`, 'utf8');
    for (const m of css.matchAll(/\/\* ([^*]+) \*\/\s*@font-face \{([\s\S]*?)\}/g)) {
      const [, label, body] = m;
      const subset = label.replace(`${pkg}-`, '').replace(`-${w}-normal`, '');
      if (keep && !keep.includes(subset)) continue;
      const cleaned = body
        .replace(/,\s*url\([^)]*\.woff\) format\('woff'\)/, '')
        .replace(/url\(\.\/files\//, `url(../../node_modules/@fontsource/${pkg}/files/`)
        .replace(/\n\s*/g, '');
      out += `@font-face{${cleaned}}\n`;
    }
  }
}
writeFileSync('src/styles/fonts.css', out);
console.log('fonts.css written:', (out.match(/@font-face/g) || []).length, 'faces');
